import path from 'node:path';
import fs from 'node:fs';
import { createStaticServer } from './tools/http-server.js';
const root = path.resolve('dist');
if (!fs.existsSync(path.join(root, 'release.json'))) throw new Error('Run npm run build first');
const port = Number(process.env.PORT || 8080);
if (!Number.isInteger(port) || port < 1 || port > 65535) throw new Error('PORT must be 1–65535');
const server = createStaticServer({ root, production: true, assetVersion: JSON.parse(fs.readFileSync(path.join(root, 'release.json'), 'utf8')).version });
server.on('error', error => { console.error(error.message); process.exitCode = 1; });
server.listen(port, process.env.HOST || '0.0.0.0', () => console.log(`RouteFlow production listening on ${port}`));
for (const signal of ['SIGTERM', 'SIGINT']) process.on(signal, () => { server.close(); server.closeIdleConnections(); });
